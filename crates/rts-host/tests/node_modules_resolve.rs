//! A bare specifier names an installed package — #2625.
//!
//! Every case below answered `None` before `graph::packages` existed, which is
//! the single symptom the issue reports: `cannot resolve module "tinypkg" —
//! nothing registered that specifier` for a package `npm install` had just put
//! on disk.
//!
//! These assert the RESOLVER rather than a running program, which is this
//! crate's rule 5 read the way the rule means it: what is under test is which
//! path a name answers, and a test that ran the program would be measuring the
//! loader, the compiler and the runtime to pin one `Option<PathBuf>`.
//! The last test in this file is the exception, and it is rule 5's own: the same
//! program RUN, so the resolved file is shown to enter the compilation as a
//! module rather than merely being found on disk.

use rts_host::graph::{resolve_written, Aliases};
use std::io::Write;
use std::path::{Path, PathBuf};

fn fixture(name: &str, files: &[(&str, &str)]) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("rts_node_modules_{name}"));
    let _ = std::fs::remove_dir_all(&dir);
    for (relative, source) in files {
        let path = dir.join(relative);
        std::fs::create_dir_all(path.parent().expect("a parent")).expect("a directory");
        let mut file = std::fs::File::create(&path).expect("a fixture file");
        file.write_all(source.as_bytes()).expect("written");
    }
    dir
}

/// Both sides canonicalised, because the resolver canonicalises its answer and
/// the temp directory is a symlink on macOS. Compared after canonicalisation
/// rather than literally, so the Windows verbatim prefix the resolver strips is
/// not what these tests are about.
fn names(found: Option<PathBuf>, expected: &Path) {
    let found = found.expect("the package resolved");
    let found = found.canonicalize().unwrap_or(found);
    let expected = expected.canonicalize().expect("the expected file exists");
    assert_eq!(found, expected);
}

/// The issue's own minimal repro, verbatim.
#[test]
fn a_bare_name_resolves_through_main() {
    let dir = fixture(
        "main",
        &[
            ("node_modules/tinypkg/package.json", "{\"name\":\"tinypkg\",\"main\":\"./index.js\"}"),
            ("node_modules/tinypkg/index.js", "export const hello = () => 1;\n"),
            ("app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("app.ts");
    names(
        resolve_written(&entry, "tinypkg", &Aliases::none()),
        &dir.join("node_modules/tinypkg/index.js"),
    );
}

/// `main` absent: the package root's `index.*`, in this crate's established
/// extension order — which is why `.ts` is the answer with both present.
#[test]
fn a_package_with_no_main_resolves_its_index() {
    let dir = fixture(
        "index",
        &[
            ("node_modules/plain/package.json", "{\"name\":\"plain\"}"),
            ("node_modules/plain/index.js", "export const x = 1;\n"),
            ("node_modules/plain/index.ts", "export const x = 1;\n"),
            ("app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("app.ts");
    names(
        resolve_written(&entry, "plain", &Aliases::none()),
        &dir.join("node_modules/plain/index.ts"),
    );
}

/// The `"exports"` map the issue asks for by name, with `"rts"` ahead of
/// `"import"`. Both targets exist here, so the answer says which condition won
/// rather than which file happened to be on disk.
#[test]
fn the_rts_condition_wins_over_import() {
    let dir = fixture(
        "condition",
        &[
            (
                "node_modules/oniwalib/package.json",
                "{\"exports\":{\".\":{\"rts\":\"./src/index.ts\",\"import\":\"./dist/index.js\",\"default\":\"./dist/index.js\"}}}",
            ),
            ("node_modules/oniwalib/src/index.ts", "export const open = () => 1;\n"),
            ("node_modules/oniwalib/dist/index.js", "export const open = () => 2;\n"),
            ("app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("app.ts");
    names(
        resolve_written(&entry, "oniwalib", &Aliases::none()),
        &dir.join("node_modules/oniwalib/src/index.ts"),
    );
}

/// A scoped package, a subpath, and a `*` pattern at once — and the longest
/// literal prefix winning, which is what keeps `"./*"` from answering first for
/// everything and making `"./lib/*"` unreachable.
#[test]
fn the_most_specific_subpath_pattern_wins() {
    let dir = fixture(
        "pattern",
        &[
            (
                "node_modules/@sc/deep/package.json",
                "{\"exports\":{\"./lib/*\":\"./dist/*.js\",\"./*\":\"./other/*.js\"}}",
            ),
            ("node_modules/@sc/deep/dist/one.js", "export const one = 1;\n"),
            ("node_modules/@sc/deep/other/one.js", "export const one = 2;\n"),
            ("app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("app.ts");
    names(
        resolve_written(&entry, "@sc/deep/lib/one", &Aliases::none()),
        &dir.join("node_modules/@sc/deep/dist/one.js"),
    );
}

/// A subpath with no `"exports"` at all is the path inside the package, through
/// the same extension rules a relative import uses.
#[test]
fn a_subpath_without_exports_is_a_path_inside_the_package() {
    let dir = fixture(
        "subpath",
        &[
            ("node_modules/tool/package.json", "{\"name\":\"tool\"}"),
            ("node_modules/tool/helpers/text.ts", "export const x = 1;\n"),
            ("app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("app.ts");
    names(
        resolve_written(&entry, "tool/helpers/text", &Aliases::none()),
        &dir.join("node_modules/tool/helpers/text.ts"),
    );
}

/// The walk goes UP, and a nearer directory that exists but answers nothing does
/// not end it. A monorepo leaves such directories behind constantly, and
/// stopping at the first one would report "no such module" for an installed one.
#[test]
fn an_empty_nearer_package_directory_does_not_end_the_walk() {
    let dir = fixture(
        "upward",
        &[
            ("node_modules/far/package.json", "{\"main\":\"./index.js\"}"),
            ("node_modules/far/index.js", "export const x = 1;\n"),
            ("packages/app/node_modules/far/.keep", ""),
            ("packages/app/app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("packages/app/app.ts");
    names(
        resolve_written(&entry, "far", &Aliases::none()),
        &dir.join("node_modules/far/index.js"),
    );
}

/// A project's own `paths` still wins over an install of the same name: the
/// alias is written by the program being compiled and the install is not.
#[test]
fn a_tsconfig_alias_wins_over_an_installed_package() {
    let dir = fixture(
        "precedence",
        &[
            (
                "tsconfig.json",
                "{\"compilerOptions\":{\"baseUrl\":\".\",\"paths\":{\"thing\":[\"./mine/thing.ts\"]}}}",
            ),
            ("mine/thing.ts", "export const x = 1;\n"),
            ("node_modules/thing/package.json", "{\"main\":\"./index.js\"}"),
            ("node_modules/thing/index.js", "export const x = 2;\n"),
            ("src/app.ts", "export const x = 1;\n"),
        ],
    );
    let entry = dir.join("src/app.ts");
    let aliases = Aliases::discover(&entry);
    names(resolve_written(&entry, "thing", &aliases), &dir.join("mine/thing.ts"));
}

/// Nothing installed still means "the host provides it by name" — the
/// established meaning of `None`, which this change must not have widened.
#[test]
fn a_name_nothing_installed_still_falls_through() {
    let dir = fixture("absent", &[("app.ts", "export const x = 1;\n")]);
    let entry = dir.join("app.ts");
    assert_eq!(resolve_written(&entry, "lodash", &Aliases::none()), None);
}

/// The same program, RUN — rule 5. The resolution above is taken the way
/// `rts run` takes it, so this fails end to end if it regresses, and it is what
/// says the resolved file actually enters the compilation as a module rather
/// than merely being found on disk.
#[test]
fn an_installed_package_runs() {
    let dir = fixture(
        "running",
        &[
            (
                "node_modules/tinypkg/package.json",
                "{\"name\":\"tinypkg\",\"exports\":{\".\":{\"rts\":\"./src/index.ts\"},\"./math\":\"./src/math.ts\"}}",
            ),
            ("node_modules/tinypkg/src/index.ts", "export const hello = (): number => 7;\n"),
            ("node_modules/tinypkg/src/math.ts", "export const twice = (n: number): number => n * 2;\n"),
            (
                "app.ts",
                "import { test, expect } from \"rts:test\";\n\
                 import { hello } from \"tinypkg\";\n\
                 import { twice } from \"tinypkg/math\";\n\
                 test(\"the package entry\", () => expect(hello()).toBe(7));\n\
                 test(\"a subpath export\", () => expect(twice(4)).toBe(8));\n",
            ),
        ],
    );
    let entry = dir.join("app.ts");
    let source = std::fs::read_to_string(&entry).expect("the fixture reads");

    rts_std::test::reset();
    assert!(
        rts_host::names_any_file(&source, &entry).expect("it parses"),
        "a bare specifier an install answers NAMES a file — the walk below depends on it"
    );
    let mut program = rts_host::compile_graph(&entry).expect("the program compiles");
    program.run();
    let reported = rts_std::test::record();
    let failed: Vec<String> = reported.iter().filter_map(|one| one.failure.clone()).collect();
    assert_eq!(reported.len(), 2, "the fixture registers two tests");
    assert!(failed.is_empty(), "the installed package ran: {failed:?}");
}
