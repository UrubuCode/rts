//! The `node:` modules, exercised the way a program reaches them.
//!
//! # Why these are here and not in `tests/suite/`
//!
//! A suite fixture ends with `return failed;`, and `return` outside a function
//! is a syntax error in a MODULE — which is what a file with an `import` is
//! parsed as. So a fixture cannot import, and the modules under test can only be
//! reached by importing them.
//!
//! These run the program instead and read what it reported through
//! `rts:test` — which makes them the first end-to-end use of that surface: the
//! import binds, the harness runs, `expect` records, and Rust reads the record.
//! A failure here is therefore ambiguous in a useful way: it means the module,
//! the import, or the harness — and all three are worth having covered.

use rts_std_rwk::test::{record, reset};

/// Runs a module and answers the names of the tests that reported a mismatch.
fn failures(source: &str) -> Vec<String> {
    reset();
    let mut program = rts_host_rwk::compile(source).expect("a module that compiles");
    program.run();
    record()
        .into_iter()
        .filter_map(|one| one.failure.map(|why| format!("{}: {why}", one.name)))
        .collect()
}

#[test]
fn path_is_string_work_and_asks_the_file_system_nothing() {
    let failed = failures(
        r#"
import { test, expect } from "rts:test";
import { join, basename, dirname, extname, isAbsolute, sep } from "node:path";

test("join", function () { expect(join("a", "b")).toBe("a/b"); });
test("join normalizes", function () { expect(join("a", "..", "b")).toBe("b"); });
test("join of nothing is the current directory", function () { expect(join()).toBe("."); });
test("basename", function () { expect(basename("/x/y/f.ts")).toBe("f.ts"); });
test("basename strips a suffix", function () { expect(basename("/x/f.ts", ".ts")).toBe("f"); });
test("basename keeps a bare suffix", function () { expect(basename(".ts", ".ts")).toBe(".ts"); });
test("dirname", function () { expect(dirname("/x/y/f.ts")).toBe("/x/y"); });
test("dirname of a bare name", function () { expect(dirname("f.ts")).toBe("."); });
test("extname", function () { expect(extname("f.test.ts")).toBe(".ts"); });
test("a dotfile has no extension", function () { expect(extname(".gitignore")).toBe(""); });
test("isAbsolute", function () { expect(isAbsolute("/x")).toBe(true); });
test("isAbsolute of a relative path", function () { expect(isAbsolute("x")).toBe(false); });
test("sep", function () { expect(sep).toBe("/"); });
"#,
    );
    assert!(failed.is_empty(), "{failed:?}");
}

#[test]
fn fs_reaches_the_real_file_system() {
    // Writes and removes what it reads, so the test leaves nothing behind. The
    // name carries the test's own so a parallel run cannot collide.
    let failed = failures(
        r#"
import { test, expect } from "rts:test";
import { existsSync, writeFileSync, readFileSync, unlinkSync, statSync } from "node:fs";

let scratch = "__rts_node_fs_probe.txt";
test("absent before", function () { expect(existsSync(scratch)).toBe(false); });
test("write then exist", function () {
    writeFileSync(scratch, "hello");
    expect(existsSync(scratch)).toBe(true);
});
test("read back", function () { expect(readFileSync(scratch, "utf8")).toBe("hello"); });
test("size is a number", function () { expect(typeof statSync(scratch).size).toBe("number"); });
test("size", function () { expect(statSync(scratch).size).toBe(5); });
test("is a file", function () { expect(statSync(scratch).isFile()).toBe(true); });
test("is not a directory", function () { expect(statSync(scratch).isDirectory()).toBe(false); });
test("removed", function () {
    unlinkSync(scratch);
    expect(existsSync(scratch)).toBe(false);
});
test("a missing read is undefined, not empty text", function () {
    expect(readFileSync("__rts_no_such_file", "utf8")).toBeUndefined();
});
"#,
    );
    assert!(failed.is_empty(), "{failed:?}");
}

