/// `node:vm` evaluates source from inside a running program, and the program
/// that called it keeps running.
///
/// The second half is the whole point. This module was written and left
/// unregistered because installing the inner program's context DESTROYED the
/// caller's — a single-slot thread-local, overwritten — so the first entry point
/// after `runInNewContext` returned found no heap and aborted the process. An
/// abort cannot be caught by an assertion, so what pins the fix is ordinary work
/// happening AFTER the evaluation: allocating an object and reading it back
/// needs the outer heap to still be there.
#[test]
fn evaluating_source_leaves_the_calling_program_running() {
    let failed = failures(
        r#"
import { test, expect } from "rts:test";
import { runInNewContext } from "node:vm";

test("a value that needs no region crosses back", function () {
    expect(runInNewContext("1 + 2")).toBe(3);
});
// The outer heap is what died before the context stack. Allocating here proves
// it did not: a fresh object, a property written and read, all after the inner
// program ran and its region went away.
test("and the caller's own heap survives it", function () {
    runInNewContext("40 + 2");
    let after = { n: 7 };
    after.n = after.n + 1;
    expect(after.n).toBe(8);
});
// A reference belongs to the region that made it, so an object built inside is
// NOT handed back. `undefined` is the honest answer and the module doc says so.
test("a reference does not cross", function () {
    expect(runInNewContext("({ a: 1 })")).toBe(undefined);
});
"#,
    );
    assert!(failed.is_empty(), "{failed:?}");
}
