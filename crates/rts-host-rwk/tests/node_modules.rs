#[test]
fn fs_promises_settle_and_a_failure_rejects() {
    // The promise half does its work synchronously and hands back a settled
    // promise — so a `.then` still runs on the microtask drain, and a failure
    // must REJECT rather than resolve. It resolved for one commit, which made a
    // success path run after a write that never happened.
    let (failed, names) = run(
        r#"
import { test, expect } from "rts:test";
import { promises, existsSync } from "node:fs";

let scratch = "__rts_node_promise_probe.txt";
test("the namespace is there", function () {
    expect(typeof promises.readFile).toBe("function");
});
test("a write lands", function () {
    promises.writeFile(scratch, "x").then(function () { test("WROTE", function () {}); });
    expect(existsSync(scratch)).toBe(true);
});
// A reaction registers a test by NAME, which is the only mark that survives the
// drain — see `run`.
test("a read of a missing file rejects", function () {
    promises.readFile("__rts_no_such_file").then(
        function () { test("READ-RESOLVED", function () {}); },
        function () { test("READ-REJECTED", function () {}); }
    );
});
test("a write into a directory that is not there rejects", function () {
    promises.writeFile("__rts_no_such_dir/x", "x").then(
        function () { test("WRITE-RESOLVED", function () {}); },
        function () { test("WRITE-REJECTED", function () {}); }
    );
});
test("cleanup", function () {
    promises.unlink(scratch);
    expect(existsSync(scratch)).toBe(false);
});
"#,
    );
    assert!(failed.is_empty(), "{failed:?}");
    // Each reaction ran. They did not for one commit, and the cause is worth
    // keeping: a host-made promise took `Promise.prototype` from whatever a
    // REGISTRATION had recorded, and a program that never writes the word
    // `Promise` has never triggered one — so the promise came back without a
    // `.then` at all, and every reaction was unreachable. `entry::settled`
    // registers the class rather than asking whether someone else did.
    for reaction in ["WROTE", "READ-REJECTED", "WRITE-REJECTED"] {
        assert!(names.contains(&reaction.to_owned()), "{reaction} did not run: {names:?}");
    }
}

