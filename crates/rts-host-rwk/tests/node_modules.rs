#[test]
fn util_inspect_prints_a_structure_where_to_string_answers_nothing() {
    let failed = failures(
        r#"
import { test, expect } from "rts:test";
import { inspect, format } from "node:util";

test("a number", function () { expect(inspect(1)).toBe("1"); });
test("a string is quoted", function () { expect(inspect("a")).toBe("'a'"); });
test("undefined", function () { expect(inspect(undefined)).toBe("undefined"); });
test("format substitutes", function () { expect(format("%s!", "a")).toBe("a!"); });
test("a leftover directive stays literal", function () { expect(format("%s %s", "a")).toBe("a %s"); });
"#,
    );
    assert!(failed.is_empty(), "{failed:?}");
}

